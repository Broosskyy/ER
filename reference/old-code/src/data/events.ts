export function getEventById(id: string): Event | undefined {
  return getPublishedEvents().find((event) => event.id === id);
}

export function getPublishedEvents(): Event[] {
  return events.filter((e) => e.lifecycleStatus === 'Published');
}

export function getFeaturedEvents(): Event[] {
  return getPublishedEvents().filter((e) => e.isFeatured);
}

export function getFeaturedEvent(): Event | undefined {
  const published = getPublishedEvents();
  return published.find((e) => e.isFeatured && e.distanceKm < 50) ?? published.find((e) => e.isFeatured);
}

export function getTonightEvents(): Event[] {
  return getPublishedEvents().filter((e) => isTodayDate(e.date)).sort((a, b) => a.distanceKm - b.distanceKm);
}

export function getRavesNearYou(maxKm = 50): Event[] {
  return getPublishedEvents().filter((e) => e.distanceKm <= maxKm).sort((a, b) => a.distanceKm - b.distanceKm);
}

export function getSimilarEvents(event: Event, limit = 3): Event[] {
  return getPublishedEvents()
    .filter(
      (e) =>
        e.id !== event.id &&
        (e.city === event.city || e.genres.some((g) => event.genres.includes(g)))
    )
    .sort((a, b) => a.distanceKm - b.distanceKm)
    .slice(0, limit);
}

export function getMapEvents(): Event[] {
  return getPublishedEvents().filter((e) => e.distanceKm < 500).sort((a, b) => a.distanceKm - b.distanceKm);
}

