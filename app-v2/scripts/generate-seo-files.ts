import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { getWebBaseUrl, INDEXABLE_STATIC_ROUTES } from '../src/platform/seo/seo-config';

const root = path.resolve(__dirname, '..');
const publicDir = path.join(root, 'public');

function escapeXml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

function buildSitemap(baseUrl: string, eventIds: string[]): string {
  const paths = [
    ...INDEXABLE_STATIC_ROUTES.map((route) => route.path),
    ...eventIds.map((id) => `/event/${encodeURIComponent(id)}`),
  ];
  const body = [...new Set(paths)].map((route) => {
    const loc = route === '/' ? baseUrl + '/' : baseUrl + route;
    // A build timestamp is not a meaningful content-modification date.
    return `  <url>
    <loc>${escapeXml(loc)}</loc>
  </url>`;
  }).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`;
}

function buildRobotsTxt(baseUrl: string): string {
  return `# Eternal Rave robots.txt — generated by scripts/generate-seo-files.ts
User-agent: *
Allow: /
Disallow: /admin/
Disallow: /admin
Disallow: /_expo/
Disallow: /assets/

Sitemap: ${baseUrl}/sitemap.xml
`;
}

function main(): void {
  const baseUrl = getWebBaseUrl();
  const eventIds = process.env.SEO_EVENT_IDS?.split(',').map((id) => id.trim()).filter(Boolean) ?? [];
  for (const id of eventIds) {
    if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(id)) {
      throw new Error('SEO_EVENT_IDS contains an invalid event UUID.');
    }
  }
  mkdirSync(publicDir, { recursive: true });
  writeFileSync(path.join(publicDir, 'sitemap.xml'), buildSitemap(baseUrl, eventIds), 'utf8');
  writeFileSync(path.join(publicDir, 'robots.txt'), buildRobotsTxt(baseUrl), 'utf8');
  console.log(`Generated absolute sitemap and robots.txt for ${baseUrl}`);
}
main();
